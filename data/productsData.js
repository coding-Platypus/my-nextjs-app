export function getFallbackProductById(id) {
  return fallbackProducts.find((p) => String(p.id) === String(id)) || null;
}

export function sanitizeProductImage(product) {
  if (!product) return null;
  const fallback = getFallbackProductById(product.id);
  // If product image is from fakestoreapi.com (which is currently Cloudflare-blocked), use reliable CDN image
  if (!product.image || product.image.includes('fakestoreapi.com/img')) {
    return {
      ...product,
      image: fallback ? fallback.image : "https://images.unsplash.com/photo-1523275335684-37898b6baf30?w=600&auto=format&fit=crop&q=80",
    };
  }
  return product;
}
